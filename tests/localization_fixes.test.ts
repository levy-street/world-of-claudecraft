// --- M1c: entity quest + NPC greeting strings keep their FULL placeholder set ---
describe('M1c: entity strings preserve every placeholder (incl {className})', () => {
  const phSet = (s: string) =>
    new Set([...String(s).matchAll(/\{([A-Za-z0-9_]+)\}/g)].map((m) => m[1]));
  function checkFields(
    enRoot: Record<string, any>,
    getLoc: (lang: string) => Record<string, any>,
    kind: string,
    fields: string[],
  ) {
    for (const lang of supportedLanguages) {
      const loc = getLoc(lang);
      for (const id of Object.keys(enRoot)) {
        for (const field of fields) {
          const ev = enRoot[id]?.[field];
          if (typeof ev !== 'string') continue;
          const enPh = phSet(ev);
          if (enPh.size === 0) continue;
          const lv = loc[id]?.[field];
          const lvPh = phSet(typeof lv === 'string' ? lv : '');
          for (const p of enPh) {
            expect(
              lvPh.has(p),
              `${lang} ${kind}.${id}.${field} dropped {${p}} (has [${[...lvPh].join(',')}])`,
            ).toBe(true);
          }
        }
      }
    }
  }
  it('quests keep text/completion placeholders', () => {
    checkFields(en.entities.quests as any, (l) => locales[l].entities.quests as any, 'quest', [
      'text',
      'completion',
    ]);
  });
  it('NPC greetings keep {className}/{playerName}', () => {
    checkFields(en.entities.npcs as any, (l) => locales[l].entities.npcs as any, 'npc', [
      'greeting',
    ]);
  });
});

