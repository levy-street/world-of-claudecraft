// Regenerate src/editor/prefab_pieces.generated.ts from data/prefab_pieces/*.json
// (written by the Tidehold installer from each building's parts GLB).
//   node scripts/gen_prefab_pieces.mjs
// Deterministic: sorted by building, fixed rounding, no timestamps.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dir = join(root, 'data', 'prefab_pieces');
const outFile = join(root, 'src', 'editor', 'prefab_pieces.generated.ts');

const defs = [];
if (existsSync(dir)) {
  for (const file of readdirSync(dir).sort()) {
    if (!file.endsWith('.json')) continue;
    const m = JSON.parse(readFileSync(join(dir, file), 'utf8'));
    defs.push({
      assetId: m.assetId,
      building: m.name,
      maxDim: m.maxDim,
      minY: m.min[1],
      shell: m.shell
        ? {
            assetId: `tidehold_parts/${m.name}/shell`,
            maxDim: m.shell.maxDim,
            minY: m.shell.min[1],
          }
        : null,
      pieces: m.pieces.map((p) => ({
        assetId: `tidehold_parts/${m.name}/${p.node}`,
        x: p.x,
        y: p.y,
        z: p.z,
        rotY: p.rotY,
        s: p.s,
        sy: p.sy,
        sz: p.sz,
        maxDim: p.maxDim,
        minY: p.min[1],
      })),
    });
  }
}

const source = `// GENERATED by scripts/gen_prefab_pieces.mjs from data/prefab_pieces/*.json - do not edit.
// ${defs.length} Blender-built buildings that Studio can split into their kit pieces.
import type { PrefabPiecesDef } from './prefab_pieces_core';

export const PREFAB_PIECES: readonly PrefabPiecesDef[] = ${JSON.stringify(defs, null, 2)};

const BY_ASSET = new Map<string, PrefabPiecesDef>(PREFAB_PIECES.map((d) => [d.assetId, d]));

/** The pieces definition for a placed building's asset id, if it has one. */
export function prefabPiecesFor(assetId: string): PrefabPiecesDef | undefined {
  return BY_ASSET.get(assetId);
}
`;
writeFileSync(outFile, source);
console.log(
  `wrote src/editor/prefab_pieces.generated.ts (${defs.length} buildings, ${defs.reduce((n, d) => n + d.pieces.length, 0)} pieces)`,
);
