#!/usr/bin/env node
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
// Local authoring pipeline. Writes reviewed source plus a shared game/server artifact.
import { build } from 'esbuild';

const target = 'src/sim/world_touchup.generated.ts';
function emit(patch, doc) {
  const sourceExpr =
    doc === null ? 'null' : `JSON.parse(${JSON.stringify(JSON.stringify(doc))}) as MapDoc`;
  return `// GENERATED by node scripts/world_touchup.mjs. Do not edit by hand.\nimport type { WorldTouchup } from './world_touchup';\nimport type { MapDoc } from './map_doc';\nexport const WORLD_TOUCHUP: WorldTouchup = ${JSON.stringify(patch, null, 2)};\nexport const WORLD_TOUCHUP_SOURCE: MapDoc | null = ${sourceExpr};\n`;
}
const [command, input, outputFlag, outputDir] = process.argv.slice(2);
if (outputFlag && (outputFlag !== '--out-dir' || !outputDir))
  throw new Error('Expected --out-dir <directory>');
const outputRoot = outputDir ?? '.';
if (command === 'init') {
  // Exclusive creation: this can never discard an existing patch.
  writeFileSync(target, emit({ version: 1, base: null, changes: {} }, null), { flag: 'wx' });
} else if (['check', 'export'].includes(command) && input) {
  const temp = mkdtempSync(path.join(tmpdir(), 'woc-world-touchup-'));
  try {
    const outfile = path.join(temp, 'compiler.mjs');
    await build({
      entryPoints: ['src/editor/live_world_core.ts'],
      bundle: true,
      platform: 'node',
      format: 'esm',
      outfile,
      logLevel: 'silent',
      define: { 'import.meta.env': '{}' },
    });
    const { compileLiveWorldDocument, publishedLiveWorldDocument } = await import(
      pathToFileURL(outfile).href
    );
    const result = compileLiveWorldDocument(readFileSync(input, 'utf8'));
    console.log(
      JSON.stringify(
        {
          base: result.patch.base,
          changedLayers: Object.keys(result.patch.changes),
          placements: result.map.placements.length,
          terrainStamps: result.map.terrainEdits.length,
        },
        null,
        2,
      ),
    );
    if (command === 'export') {
      const source = publishedLiveWorldDocument(result.map, result.patch);
      mkdirSync(path.join(outputRoot, 'data/world_touchup'), { recursive: true });
      mkdirSync(path.join(outputRoot, 'src/sim'), { recursive: true });
      writeFileSync(
        path.join(outputRoot, 'data/world_touchup/current.map.json'),
        `${JSON.stringify(source, null, 2)}\n`,
      );
      writeFileSync(path.join(outputRoot, target), emit(result.patch, source));
      console.log(
        'Wrote local source and runtime artifact. Review the diff and test before merging or deploying.',
      );
    }
  } finally {
    rmSync(temp, { recursive: true, force: true });
  }
} else {
  console.error('Usage: node scripts/world_touchup.mjs check|export <editor-map.json>');
  process.exitCode = 1;
}
