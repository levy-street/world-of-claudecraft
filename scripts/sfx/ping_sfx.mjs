const SAMPLE_RATE = 44100;
const r6 = (value) => Number(value.toFixed(6));

/** The ffmpeg -filter_complex for one recipe, inputs in `inputs` order (one
 *  input per distinct source). The mix is high-passed, lightly glued, limited
 *  and cut at `length` with a short fade; the builder sets the final level. */
export function pingFilterGraph(recipe, inputs) {
  const parts = [];
  recipe.layers.forEach((spec, index) => {
    const input = inputs.indexOf(spec.src);
    if (input < 0) throw new Error(`ping layer source ${spec.src} is not an input`);
    const rate = 2 ** (spec.semis / 12);
    const duration = (spec.end - spec.start) / rate;
    const chain = [
      `atrim=start=${spec.start}:end=${spec.end}`,
      'asetpts=PTS-STARTPTS',
      'aformat=sample_fmts=fltp:channel_layouts=mono',
    ];
    if (spec.semis) {
      chain.push(`asetrate=${r6(SAMPLE_RATE * rate)}`, `aresample=${SAMPLE_RATE}`);
    }
    if (spec.highpassHz) chain.push(`highpass=f=${spec.highpassHz}`);
    if (spec.lowpassHz) chain.push(`lowpass=f=${spec.lowpassHz}`);
    if (spec.tremoloHz) chain.push(`tremolo=f=${spec.tremoloHz}:d=${spec.tremoloDepth}`);
    if (spec.fadeInMs) chain.push(`afade=t=in:d=${r6(spec.fadeInMs / 1000)}:curve=qsin`);
    if (spec.fadeOutMs) {
      const fade = Math.min(spec.fadeOutMs / 1000, duration);
      chain.push(`afade=t=out:st=${r6(duration - fade)}:d=${r6(fade)}:curve=${spec.fadeOutCurve}`);
    }
    chain.push(`volume=${spec.gain}`);
    if (spec.delayMs) chain.push(`adelay=${spec.delayMs}:all=1`);
    parts.push(`[${input}:a]${chain.join(',')}[l${index}]`);
  });
  const labels = recipe.layers.map((_, index) => `[l${index}]`).join('');
  const tail = 0.08;
  parts.push(
    `${labels}amix=inputs=${recipe.layers.length}:normalize=0:duration=longest,` +
      'highpass=f=40,' +
      `volume=${recipe.driveDb ?? 0}dB,` +
      'acompressor=threshold=0.18:ratio=2:attack=4:release=120:knee=4,' +
      'alimiter=limit=0.75:attack=2:release=60:level=false,' +
      `atrim=end=${recipe.length},` +
      `afade=t=out:st=${r6(recipe.length - tail)}:d=${tail}:curve=qsin[out]`,
  );
  return parts.join(';');
}
