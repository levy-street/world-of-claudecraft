/** A layer: `src` (a PING_SOURCES role), the [start, end) slice, a pitch
 *  shift in semitones (speed follows, as a rate change), the level, fades
 *  (the fade-out's ffmpeg curve too: `qua` falls like a natural decay),
 *  filters and an optional tremolo, and when it enters the mix. */
const layer = (src, start, end, opts = {}) => ({
  src,
  start,
  end,
  semis: 0,
  gain: 1,
  delayMs: 0,
  fadeInMs: 0,
  fadeOutMs: 0,
  highpassHz: 0,
  lowpassHz: 0,
  tremoloHz: 0,
  tremoloDepth: 0,
  fadeOutCurve: 'qsin',
  ...opts,
});

