// Build the shipped grand ferry from its art source, generate the collision
// plan measured off it, optimize, and prove the two agree.
//
// Usage:
//   node scripts/assets/grand_ferry_ship/export_grand_ferry_ship.mjs --no-preview
//   node scripts/assets/grand_ferry_ship/export_grand_ferry_ship.mjs --raw-only --no-preview
//   node scripts/assets/grand_ferry_ship/export_grand_ferry_ship.mjs --verify-staged --no-preview
//
// The pipeline is: art GLB -> scripted edits -> measure -> plan -> optimize.
// Nothing here authors geometry by hand and nothing types a collision number,
// so a new hull is a new file in source/ plus whatever intent changes in
// build.mjs, and the walkable plan follows automatically.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getBounds } from '@gltf-transform/core';
import { closePreview, renderPreviews } from '../../asset_pipeline/lib/preview.mjs';
import { decompressForEditing, documentTriangles, glbIO } from '../lib/glb_geometry.mjs';
import { buildGrandFerry } from './build.mjs';
import { grandFerryShipSourceFingerprint } from './source_fingerprint.mjs';
import { verifyPlanAgainstMesh } from './verify.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..', '..');
const SPEC = path.join(ROOT, 'scripts/assets/specs/grand_ferry_ship.json');
const BUILD_ASSETS = path.join(ROOT, 'scripts/assets/build_assets.mjs');
const GENERATED_PLAN = path.join(ROOT, 'src/sim/grand_ferry_ship_plan.generated.ts');
const RAW_OUT = path.join(ROOT, 'tmp/asset_src/grand_ferry_ship/grand_ferry_ship-final.glb');
const SHIPPING_OUT = path.join(ROOT, 'public/models/props/grand_ferry_ship.glb');
const CANDIDATE_ROOT = path.join(ROOT, 'tmp/asset_optimized/grand_ferry_ship/candidate');
const REPEAT_ROOT = path.join(ROOT, 'tmp/asset_optimized/grand_ferry_ship/repeat');
const CANDIDATE_OUT = path.join(CANDIDATE_ROOT, 'models/props/grand_ferry_ship.glb');
const REPEAT_OUT = path.join(REPEAT_ROOT, 'models/props/grand_ferry_ship.glb');

const rawOnly = process.argv.includes('--raw-only');
const noPreview = process.argv.includes('--no-preview');
const verifyStaged = process.argv.includes('--verify-staged');
if (verifyStaged && rawOnly) {
  throw new Error('--verify-staged cannot be combined with --raw-only');
}

/** The deck the build lays is the one mesh this pipeline generates; the rest
 *  is the artist's. Both must survive to the shipped file. */
const REQUIRED_MESHES = Object.freeze(['GrandFerryDeck']);
const TRIANGLE_CEILING = 12_000;
const SHIPPING_BYTE_CEILING = 320 * 1024;

function assertCondition(condition, message) {
  if (!condition) throw new Error(message);
}

function quoteString(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

function tsLiteral(value, indent = 0) {
  if (value === null) return 'null';
  if (typeof value === 'number') {
    assertCondition(Number.isFinite(value), 'generated ferry plan contains a non-finite number');
    return Object.is(value, -0) ? '0' : String(value);
  }
  if (typeof value === 'string') return quoteString(value);
  if (typeof value === 'boolean') return String(value);
  const pad = ' '.repeat(indent);
  const childPad = ' '.repeat(indent + 2);
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return `[\n${value.map((entry) => `${childPad}${tsLiteral(entry, indent + 2)},`).join('\n')}\n${pad}]`;
  }
  const entries = Object.entries(value).filter(([, entry]) => entry !== undefined);
  if (entries.length === 0) return '{}';
  return `{\n${entries
    .map(([key, entry]) => `${childPad}${key}: ${tsLiteral(entry, indent + 2)},`)
    .join('\n')}\n${pad}}`;
}

function writeGeneratedPlan(plan) {
  const source = [
    '// Generated by scripts/assets/grand_ferry_ship/export_grand_ferry_ship.mjs.',
    '// Do not edit by hand. Regenerate through the ferry exporter.',
    '//',
    '// Every value here was MEASURED off the shipped mesh, not authored. See',
    '// scripts/assets/grand_ferry_ship/build.mjs for how, and the contract test',
    '// tests/grand_ferry_ship_asset.test.ts for the proof that they still agree.',
    '',
    `export const GRAND_FERRY_SHIP_PLAN = ${tsLiteral(plan)} as const;`,
    '',
  ].join('\n');
  writeFileSync(GENERATED_PLAN, source);
  return Buffer.from(source);
}

async function stampSourceFingerprint(glbPath, sourceFingerprint) {
  const io = glbIO();
  const document = await io.read(glbPath);
  const root = document.getRoot();
  root.setExtras({ ...root.getExtras(), sourceFingerprint });
  const asset = root.getAsset();
  const extras =
    asset.extras && typeof asset.extras === 'object' && !Array.isArray(asset.extras)
      ? asset.extras
      : {};
  asset.extras = { ...extras, sourceFingerprint };
  await io.write(glbPath, document);
}

async function inspectGlb(glbPath) {
  const document = await glbIO().read(glbPath);
  const root = document.getRoot();
  const scene = root.getDefaultScene() ?? root.listScenes()[0];
  if (!scene) throw new Error(`${glbPath} has no scene`);
  const triangles = documentTriangles(document);
  return {
    path: path.relative(ROOT, glbPath),
    bytes: statSync(glbPath).size,
    sha256: createHash('sha256').update(readFileSync(glbPath)).digest('hex'),
    scenes: root.listScenes().length,
    meshes: root.listMeshes().map((mesh) => mesh.getName()),
    materials: root.listMaterials().length,
    textures: root.listTextures().length,
    animations: root.listAnimations().length,
    skins: root.listSkins().length,
    triangles: triangles.length,
    bounds: getBounds(scene),
    fingerprint: root.getExtras()?.sourceFingerprint,
    geometry: triangles,
  };
}

/** The shipped-file contract, plus the one that matters: the collision plan
 *  still describes this exact geometry. */
function verifyGlbContract(stats, plan, optimized, sourceFingerprint) {
  assertCondition(stats.scenes === 1, `${stats.path} must contain one scene`);
  for (const name of REQUIRED_MESHES) {
    assertCondition(stats.meshes.includes(name), `${stats.path} lost ${name}`);
  }
  assertCondition(
    stats.triangles <= TRIANGLE_CEILING,
    `${stats.path} exceeds the triangle ceiling: ${stats.triangles}`,
  );
  assertCondition(
    stats.animations === 0 && stats.skins === 0,
    `${stats.path} gained animations or skins`,
  );
  assertCondition(
    stats.fingerprint === sourceFingerprint,
    `${stats.path} source fingerprint changed or is missing`,
  );
  if (optimized) {
    assertCondition(
      stats.bytes <= SHIPPING_BYTE_CEILING,
      `${stats.path} exceeds the byte ceiling: ${stats.bytes}`,
    );
  }
  const epsilon = optimized ? plan.measurementEpsilons.optimized : plan.measurementEpsilons.raw;
  const { problems, stats: measured } = verifyPlanAgainstMesh(stats.geometry, plan, {
    boundsEpsilon: epsilon,
    surfaceTolerance: 0.25 + epsilon,
  });
  assertCondition(
    problems.length === 0,
    `${stats.path} disagrees with the collision plan:\n  - ${problems.join('\n  - ')}`,
  );
  return measured;
}

function runOptimizer(outputRoot = null) {
  const args = [BUILD_ASSETS, SPEC];
  if (outputRoot) args.push('--output-root', outputRoot);
  const result = spawnSync(process.execPath, args, {
    cwd: ROOT,
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024,
  });
  if (result.stdout) process.stdout.write(result.stdout);
  if (result.stderr) process.stderr.write(result.stderr);
  if (result.status !== 0) {
    throw new Error(`grand ferry optimizer failed: ${result.status ?? 'unknown'}`);
  }
}

function stagedFile(relativePath, maxBuffer = 16 * 1024 * 1024) {
  const result = spawnSync('git', ['cat-file', 'blob', `:${relativePath}`], {
    cwd: ROOT,
    encoding: null,
    maxBuffer,
  });
  if (result.status !== 0 || !Buffer.isBuffer(result.stdout)) {
    throw new Error(`cannot read staged ${relativePath}`);
  }
  return result.stdout;
}

async function capturePreviews() {
  try {
    for (const [source, target] of [
      [RAW_OUT, 'tmp/grand_ferry_ship_preview/raw'],
      [SHIPPING_OUT, 'tmp/grand_ferry_ship_preview/optimized'],
    ]) {
      const files = await renderPreviews(source, path.join(ROOT, target), {
        size: 768,
        views: ['front', 'right', 'back', 'left', 'hero'],
        clips: false,
      });
      for (const file of files) console.log(`preview: ${path.relative(ROOT, file)}`);
    }
  } finally {
    await closePreview();
  }
}

const { document, plan, report } = await buildGrandFerry();
console.log(
  `built: ${report.deckRects.length} deck section(s), ${report.plankCount} planks, ` +
    `${report.gangwayTrianglesRemoved} triangles cut for the gangway`,
);
const generatedPlanBytes = writeGeneratedPlan(plan);
mkdirSync(path.dirname(RAW_OUT), { recursive: true });
await glbIO().write(RAW_OUT, decompressForEditing(document));
console.log(`raw: ${path.relative(ROOT, RAW_OUT)}`);

const sourceFingerprint = grandFerryShipSourceFingerprint(ROOT);
await stampSourceFingerprint(RAW_OUT, sourceFingerprint);
const rawStats = await inspectGlb(RAW_OUT);
const rawMeasured = verifyGlbContract(rawStats, plan, false, sourceFingerprint);
console.log(
  `raw validated: ${rawStats.triangles} tris, ${rawMeasured.supported} supported / ` +
    `${rawMeasured.blocked} blocked / ${rawMeasured.holes} holes`,
);

if (!rawOnly) {
  runOptimizer(CANDIDATE_ROOT);
  runOptimizer(REPEAT_ROOT);
  const candidateBytes = readFileSync(CANDIDATE_OUT);
  const repeatBytes = readFileSync(REPEAT_OUT);
  assertCondition(candidateBytes.equals(repeatBytes), 'optimization is nondeterministic');
  const candidateStats = await inspectGlb(CANDIDATE_OUT);
  verifyGlbContract(candidateStats, plan, true, sourceFingerprint);

  if (verifyStaged) {
    assertCondition(
      candidateBytes.equals(stagedFile('public/models/props/grand_ferry_ship.glb')),
      'staged grand ferry GLB differs from deterministic rebuild',
    );
    assertCondition(
      generatedPlanBytes.equals(stagedFile('src/sim/grand_ferry_ship_plan.generated.ts')),
      'staged grand ferry plan differs from deterministic regeneration',
    );
    console.log(`staged artifact verified: ${candidateStats.sha256}`);
  } else {
    runOptimizer();
    assertCondition(
      candidateBytes.equals(readFileSync(SHIPPING_OUT)),
      'shipping grand ferry differs from deterministic candidate',
    );
    const shippingStats = await inspectGlb(SHIPPING_OUT);
    const shippingMeasured = verifyGlbContract(shippingStats, plan, true, sourceFingerprint);
    console.log(
      `optimized validated: ${shippingStats.bytes} bytes, ${shippingStats.triangles} tris, ` +
        `${shippingMeasured.holes} holes`,
    );
    console.log(`deterministic optimized rebuild: ${shippingStats.sha256}`);
    if (!noPreview) await capturePreviews();
  }
}

console.log(`source fingerprint: ${sourceFingerprint}`);
