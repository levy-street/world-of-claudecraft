function assertCondition(condition, message) {
  if (!condition) throw new Error(message);
}

function assertApprox(actual, expected, label, epsilon) {
  assertCondition(
    Math.abs(actual - expected) <= epsilon,
    `${label} expected ${expected}, got ${actual}`,
  );
}

function assertApproxArray(actual, expected, label, epsilon) {
  assertCondition(actual.length === expected.length, `${label} length changed`);
  for (let index = 0; index < expected.length; index++) {
    assertApprox(actual[index], expected[index], `${label}[${index}]`, epsilon);
  }
}

function quoteString(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

function tsLiteral(value, indent = 0) {
  if (value === null) return 'null';
  if (typeof value === 'number') {
    assertCondition(Number.isFinite(value), 'generated ferry plan contains a non-finite number');
    return Object.is(value, -0) ? '0' : String(value);
  }
  if (typeof value === 'string') return quoteString(value);
  if (typeof value === 'boolean') return String(value);
  const pad = ' '.repeat(indent);
  const childPad = ' '.repeat(indent + 2);
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return `[\n${value.map((entry) => `${childPad}${tsLiteral(entry, indent + 2)},`).join('\n')}\n${pad}]`;
  }
  const entries = Object.entries(value);
  if (entries.length === 0) return '{}';
  return `{\n${entries
    .map(([key, entry]) => `${childPad}${key}: ${tsLiteral(entry, indent + 2)},`)
    .join('\n')}\n${pad}}`;
}

function generatedPlanSource() {
  return [
    '// Generated by scripts/assets/grand_ferry_ship/export_grand_ferry_ship.mjs.',
    '// Do not edit by hand. Regenerate through the ferry exporter.',
    '',
    `export const GRAND_FERRY_SHIP_PLAN = ${tsLiteral(GRAND_FERRY_SHIP_PLAN)} as const;`,
    '',
  ].join('\n');
}

function writeGeneratedPlan() {
  const source = generatedPlanSource();
  writeFileSync(GENERATED_PLAN, source);
  return Buffer.from(source);
}

function verifyAuthoringMeasurements(stats) {
  const epsilon = GRAND_FERRY_SHIP_PLAN.measurementEpsilons.raw;
  const native = GRAND_FERRY_SHIP_NATIVE_BOUNDS;
  assertApproxArray(
    stats.bounds.min,
    [-native.length / 2, native.keelY, -native.beam / 2],
    'factory bounds min',
    epsilon,
  );
  assertApproxArray(
    stats.bounds.max,
    [native.length / 2, native.height, native.beam / 2],
    'factory bounds max',
    epsilon,
  );
  assertCondition(stats.meshes === MESH_NAMES.length, 'factory semantic mesh count changed');
  assertCondition(stats.materials === MATERIAL_NAMES.length, 'factory material count changed');
  assertCondition(stats.triangles <= TRIANGLE_CEILING, 'factory exceeds triangle ceiling');
  const deck = GRAND_FERRY_SHIP_PLAN.deck;
  const deckBounds = stats.semanticBounds.GrandFerryMainDeck;
  assertCondition(deckBounds, 'factory lost GrandFerryMainDeck');
  assertApproxArray(
    deckBounds.min,
    [deck.x - deck.hw, deck.y - deck.thickness, deck.z - deck.hd],
    'factory deck bounds min',
    epsilon,
  );
  assertApproxArray(
    deckBounds.max,
    [deck.x + deck.hw, deck.y, deck.z + deck.hd],
    'factory deck bounds max',
    epsilon,
  );
  assertCondition(stats.railOpeningIntrusions === 0, 'factory rail mesh closes the gangway gap');
  const edge = GRAND_FERRY_SHIP_PLAN.rampMatingEdge;
  assertApproxArray(
    stats.socketPositions.Socket_GangwayMatingEdge,
    [edge.x, edge.y, edge.z],
    'factory gangway mating socket',
    epsilon,
  );
  const superstructure = GRAND_FERRY_SHIP_PLAN.blockingVolumes.find(
    (volume) => volume.kind === 'superstructure',
  );
  const superstructureBounds = stats.semanticBounds.GrandFerrySuperstructure;
  assertCondition(superstructure, 'factory plan lost the superstructure blocker');
  assertCondition(superstructureBounds, 'factory lost GrandFerrySuperstructure');
  assertApproxArray(
    [superstructureBounds.min[0], superstructureBounds.min[2]],
    [superstructure.x - superstructure.hw, superstructure.z - superstructure.hd],
    'factory superstructure bounds min',
    epsilon,
  );
  assertApproxArray(
    [superstructureBounds.max[0], superstructureBounds.max[2]],
    [superstructure.x + superstructure.hw, superstructure.z + superstructure.hd],
    'factory superstructure bounds max',
    epsilon,
  );
}

async function createNodeIo() {
  await MeshoptDecoder.ready;
  return new NodeIO()
    .registerExtensions(ALL_EXTENSIONS)
    .registerDependencies({ 'meshopt.decoder': MeshoptDecoder });
}

function fingerprintExtras(root) {
  return {
    document: root.getExtras()?.sourceFingerprint,
    asset: root.getAsset().extras?.sourceFingerprint,
  };
}

async function stampSourceFingerprint(glbPath, sourceFingerprint) {
  const io = await createNodeIo();
  const document = await io.read(glbPath);
  const root = document.getRoot();
  root.setExtras({ ...root.getExtras(), sourceFingerprint });
  const asset = root.getAsset();
  const extras =
    asset.extras && typeof asset.extras === 'object' && !Array.isArray(asset.extras)
      ? asset.extras
      : {};
  asset.extras = { ...extras, sourceFingerprint };
  await io.write(glbPath, document);
}

async function inspectGlb(glbPath) {
  const io = await createNodeIo();
  const document = await io.read(glbPath);
  const root = document.getRoot();
  const scene = root.listScenes()[0];
  if (!scene) throw new Error(`${glbPath} has no scene`);
  const meshes = root
    .listNodes()
    .filter((node) => node.getMesh())
    .map((node) => {
      const bounds = getBounds(node);
      return {
        name: node.getName(),
        primitives: node
          .getMesh()
          .listPrimitives()
          .map((primitive) => {
            const position = primitive.getAttribute('POSITION');
            if (!position) throw new Error(`${node.getName()} has no POSITION`);
            return {
              material: primitive.getMaterial()?.getName() ?? null,
              mode: primitive.getMode(),
              attributes: primitive.listSemantics().sort(),
              triangles: (primitive.getIndices()?.getCount() ?? position.getCount()) / 3,
              bounds,
            };
          }),
      };
    });
  const modelRoot = root.listNodes().find((node) => node.getName() === 'GrandFerryShip');
  const sockets = root
    .listNodes()
    .filter((node) => node.getName().startsWith('Socket_'))
    .map((node) => ({
      name: node.getName(),
      translation: node.getTranslation(),
      children: node.listChildren().length,
      mesh: node.getMesh()?.getName() ?? null,
      extras: node.getExtras(),
    }))
    .sort((left, right) => left.name.localeCompare(right.name));
  return {
    path: path.relative(ROOT, glbPath),
    bytes: statSync(glbPath).size,
    sha256: createHash('sha256').update(readFileSync(glbPath)).digest('hex'),
    usedExtensions: root
      .listExtensionsUsed()
      .map((extension) => extension.extensionName)
      .sort(),
    requiredExtensions: root
      .listExtensionsRequired()
      .map((extension) => extension.extensionName)
      .sort(),
    scenes: root.listScenes().length,
    sceneChildren: scene.listChildren().map((node) => node.getName()),
    meshes,
    triangles: meshes.reduce(
      (sum, mesh) =>
        sum + mesh.primitives.reduce((meshSum, primitive) => meshSum + primitive.triangles, 0),
      0,
    ),
    materials: root
      .listMaterials()
      .map((material) => material.getName())
      .sort(),
    textures: root.listTextures().length,
    animations: root.listAnimations().length,
    skins: root.listSkins().length,
    cameras: root.listCameras().length,
    bounds: getBounds(scene),
    modelRoot: modelRoot
      ? {
          translation: modelRoot.getTranslation(),
          rotation: modelRoot.getRotation(),
          scale: modelRoot.getScale(),
          extras: modelRoot.getExtras(),
        }
      : null,
    sockets,
    fingerprints: fingerprintExtras(root),
  };
}

function primitiveFor(stats, meshName) {
  const mesh = stats.meshes.find((candidate) => candidate.name === meshName);
  assertCondition(mesh, `${stats.path} lost ${meshName}`);
  assertCondition(mesh.primitives.length === 1, `${meshName} must have one primitive`);
  return mesh.primitives[0];
}

function verifyGlbContract(stats, optimized, sourceFingerprint) {
  const expectedExtensions = optimized ? ['EXT_meshopt_compression', 'KHR_mesh_quantization'] : [];
  assertCondition(
    JSON.stringify(stats.usedExtensions) === JSON.stringify(expectedExtensions),
    `${stats.path} used extensions changed: ${stats.usedExtensions.join(', ')}`,
  );
  assertCondition(
    JSON.stringify(stats.requiredExtensions) === JSON.stringify(expectedExtensions),
    `${stats.path} required extensions changed: ${stats.requiredExtensions.join(', ')}`,
  );
  assertCondition(
    !stats.usedExtensions.includes('KHR_draco_mesh_compression'),
    'Draco is forbidden',
  );
  assertCondition(
    !stats.usedExtensions.includes('KHR_lights_punctual'),
    'GLB lights are forbidden',
  );
  assertCondition(stats.scenes === 1, `${stats.path} must contain one scene`);
  assertCondition(
    JSON.stringify(stats.sceneChildren) === JSON.stringify(['GrandFerryShip']),
    `${stats.path} scene root changed`,
  );
  assertCondition(
    JSON.stringify(stats.meshes.map((mesh) => mesh.name).sort()) === JSON.stringify(MESH_NAMES),
    `${stats.path} semantic meshes changed`,
  );
  assertCondition(
    stats.meshes.every(
      (mesh) =>
        mesh.primitives.length === 1 &&
        mesh.primitives[0].mode === Primitive.Mode.TRIANGLES &&
        JSON.stringify(mesh.primitives[0].attributes) ===
          JSON.stringify(['COLOR_0', 'NORMAL', 'POSITION']),
    ),
    `${stats.path} mesh topology contract changed`,
  );
  assertCondition(stats.triangles <= TRIANGLE_CEILING, `${stats.path} exceeds triangle ceiling`);
  assertCondition(
    JSON.stringify(stats.materials) === JSON.stringify(MATERIAL_NAMES),
    `${stats.path} material names changed`,
  );
  assertCondition(
    stats.textures === 0 && stats.animations === 0 && stats.skins === 0 && stats.cameras === 0,
    `${stats.path} gained textures, animations, skins, or cameras`,
  );
  if (optimized) {
    assertCondition(stats.bytes <= SHIPPING_BYTE_CEILING, `${stats.path} exceeds byte ceiling`);
  }
  const epsilon = optimized
    ? GRAND_FERRY_SHIP_PLAN.measurementEpsilons.optimized
    : GRAND_FERRY_SHIP_PLAN.measurementEpsilons.raw;
  const native = GRAND_FERRY_SHIP_NATIVE_BOUNDS;
  assertApproxArray(
    stats.bounds.min,
    [-native.length / 2, native.keelY, -native.beam / 2],
    `${stats.path} bounds min`,
    epsilon,
  );
  assertApproxArray(
    stats.bounds.max,
    [native.length / 2, native.height, native.beam / 2],
    `${stats.path} bounds max`,
    epsilon,
  );
  const deck = GRAND_FERRY_SHIP_PLAN.deck;
  const deckPrimitive = primitiveFor(stats, 'GrandFerryMainDeck');
  assertApproxArray(
    deckPrimitive.bounds.min,
    [deck.x - deck.hw, deck.y - deck.thickness, deck.z - deck.hd],
    `${stats.path} deck bounds min`,
    epsilon,
  );
  assertApproxArray(
    deckPrimitive.bounds.max,
    [deck.x + deck.hw, deck.y, deck.z + deck.hd],
    `${stats.path} deck bounds max`,
    epsilon,
  );
  const superstructure = GRAND_FERRY_SHIP_PLAN.blockingVolumes.find(
    (volume) => volume.kind === 'superstructure',
  );
  assertCondition(superstructure, 'factory plan lost the superstructure blocker');
  const superstructurePrimitive = primitiveFor(stats, 'GrandFerrySuperstructure');
  assertApproxArray(
    [superstructurePrimitive.bounds.min[0], superstructurePrimitive.bounds.min[2]],
    [superstructure.x - superstructure.hw, superstructure.z - superstructure.hd],
    `${stats.path} superstructure bounds min`,
    epsilon,
  );
  assertApproxArray(
    [superstructurePrimitive.bounds.max[0], superstructurePrimitive.bounds.max[2]],
    [superstructure.x + superstructure.hw, superstructure.z + superstructure.hd],
    `${stats.path} superstructure bounds max`,
    epsilon,
  );
  assertCondition(stats.modelRoot, `${stats.path} has no GrandFerryShip root`);
  assertApproxArray(stats.modelRoot.translation, [0, 0, 0], `${stats.path} root translation`, 1e-8);
  assertApproxArray(stats.modelRoot.rotation, [0, 0, 0, 1], `${stats.path} root rotation`, 1e-8);
  assertApproxArray(stats.modelRoot.scale, [1, 1, 1], `${stats.path} root scale`, 1e-8);
  assertCondition(
    stats.modelRoot.extras.sculptRuntime?.source === 'deterministic-procedural-threejs',
    `${stats.path} lost procedural source metadata`,
  );
  assertCondition(
    stats.modelRoot.extras.sculptRuntime?.shippingCollisionMesh === false,
    `${stats.path} gained shipping collision geometry`,
  );
  const edge = GRAND_FERRY_SHIP_PLAN.rampMatingEdge;
  const gangwaySocket = stats.sockets.find((socket) => socket.name === 'Socket_GangwayMatingEdge');
  assertCondition(gangwaySocket, `${stats.path} lost Socket_GangwayMatingEdge`);
  assertCondition(
    gangwaySocket.children === 0 && gangwaySocket.mesh === null,
    'gangway mating socket must stay empty',
  );
  assertApproxArray(
    gangwaySocket.translation,
    [edge.x, edge.y, edge.z],
    `${stats.path} gangway mating socket`,
    epsilon,
  );
  assertCondition(
    stats.fingerprints.document === sourceFingerprint &&
      stats.fingerprints.asset === sourceFingerprint,
    `${stats.path} source fingerprint changed or is missing`,
  );
}

function runOptimizer(outputRoot = null) {
  const args = [BUILD_ASSETS, SPEC];
  if (outputRoot) args.push('--output-root', outputRoot);
  const result = spawnSync(process.execPath, args, {
    cwd: ROOT,
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024,
  });
  if (result.stdout) process.stdout.write(result.stdout);
  if (result.stderr) process.stderr.write(result.stderr);
  if (result.status !== 0) {
    throw new Error(`grand ferry optimizer failed: ${result.status ?? 'unknown'}`);
  }
}

function stagedFile(relativePath, maxBuffer = 16 * 1024 * 1024) {
  const result = spawnSync('git', ['cat-file', 'blob', `:${relativePath}`], {
    cwd: ROOT,
    encoding: null,
    maxBuffer,
  });
  if (result.status !== 0 || !Buffer.isBuffer(result.stdout)) {
    throw new Error(`cannot read staged ${relativePath}`);
  }
  return result.stdout;
}

async function capturePreviews() {
  try {
    const rawFiles = await renderPreviews(
      RAW_OUT,
      path.join(ROOT, 'tmp/grand_ferry_ship_preview/raw'),
      {
        size: 768,
        views: ['front', 'right', 'back', 'left', 'hero'],
        clips: false,
      },
    );
    const optimizedFiles = await renderPreviews(
      SHIPPING_OUT,
      path.join(ROOT, 'tmp/grand_ferry_ship_preview/optimized'),
      {
        size: 768,
        views: ['front', 'right', 'back', 'left', 'hero'],
        clips: false,
      },
    );
    for (const file of [...rawFiles, ...optimizedFiles]) {
      console.log(`preview: ${path.relative(ROOT, file)}`);
    }
  } finally {
    await closePreview();
  }
}

const generatedPlanBytes = writeGeneratedPlan();
const { glb, stats: authoringStats } = await exportGrandFerryShipGlb();
verifyAuthoringMeasurements(authoringStats);
mkdirSync(path.dirname(RAW_OUT), { recursive: true });
writeFileSync(RAW_OUT, Buffer.from(glb));
console.log(`raw: ${path.relative(ROOT, RAW_OUT)}`);
console.log(`authoring stats: ${JSON.stringify(authoringStats)}`);

const sourceFingerprint = grandFerryShipSourceFingerprint(ROOT);
await stampSourceFingerprint(RAW_OUT, sourceFingerprint);
const rawStats = await inspectGlb(RAW_OUT);
verifyGlbContract(rawStats, false, sourceFingerprint);
console.log(`raw validated: ${JSON.stringify(rawStats)}`);

if (!rawOnly) {
  runOptimizer(CANDIDATE_ROOT);
  runOptimizer(REPEAT_ROOT);
  const candidateBytes = readFileSync(CANDIDATE_OUT);
  const repeatBytes = readFileSync(REPEAT_OUT);
  assertCondition(
    candidateBytes.equals(repeatBytes),
    `optimization is nondeterministic: ${createHash('sha256').update(candidateBytes).digest('hex')} != ${createHash('sha256').update(repeatBytes).digest('hex')}`,
  );
  const candidateStats = await inspectGlb(CANDIDATE_OUT);
  verifyGlbContract(candidateStats, true, sourceFingerprint);

  if (verifyStaged) {
    assertCondition(
      candidateBytes.equals(stagedFile('public/models/props/grand_ferry_ship.glb')),
      'staged grand ferry GLB differs from deterministic rebuild',
    );
    assertCondition(
      generatedPlanBytes.equals(stagedFile('src/sim/grand_ferry_ship_plan.generated.ts')),
      'staged grand ferry plan differs from deterministic regeneration',
    );
    console.log(`staged artifact verified: ${candidateStats.sha256}`);
  } else {
    runOptimizer();
    assertCondition(
      candidateBytes.equals(readFileSync(SHIPPING_OUT)),
      'shipping grand ferry differs from deterministic candidate',
    );
    const shippingStats = await inspectGlb(SHIPPING_OUT);
    verifyGlbContract(shippingStats, true, sourceFingerprint);
    console.log(`optimized validated: ${JSON.stringify(shippingStats)}`);
    console.log(`deterministic optimized rebuild: ${shippingStats.sha256}`);
    if (!noPreview) await capturePreviews();
  }
}

