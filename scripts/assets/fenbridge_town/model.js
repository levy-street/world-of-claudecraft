export function createFenbridgeTownAsset(assetId) {
  const contract = FENBRIDGE_TOWN_CONTRACTS[assetId];
  if (!contract) throw new Error(`unknown Fenbridge town asset: ${assetId}`);
  const buckets = createFenbridgeBuckets();
  contract.build(buckets);
  return finishFenbridgeAsset(contract, buckets);
}
