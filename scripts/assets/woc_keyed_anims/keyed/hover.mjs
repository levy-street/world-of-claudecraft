function hover(table) {
  return {
    clip(fit, model) {
      const { duration, keys } = table[fit];
      const key = beats(model);
      const authored = keys.map(({ t, ...b }) => key(t, { clav: { l: [0, 0], r: [0, 0] }, ...b }));
      return {
        duration,
        loop: true,
        family: 'hover',
        // Arms hang or reach straight overhead, where raise/plane angles wrap;
        // forward/sideways swing angles stay continuous there.
        armForm: 'swing',
        bladeTravel: 'arm',
        bladeSteady: 6,
        bladeLimits: { flex: [-75, 85], dev: [-50, 30] },
        keys: [...authored, { ...authored[0], t: duration }],
        lag: { head: 0.05, neck: 0.04 },
      };
    },
  };
}

