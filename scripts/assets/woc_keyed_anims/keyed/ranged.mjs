// Side-on stances: [lead pos, lead yaw, rear pos, rear yaw].
const STANCE = {
  rifleMale: [[0.08, 0, 0.159], -11, [-0.042, 0, -0.224], 42],
  rifleFemale: [[0.142, 0, 0.171], -25, [-0.118, 0, -0.236], 40],
  bowMale: [[0.08, 0, 0.16], -11, [-0.04, 0, -0.225], 42],
  bowFemale: [[0.154, 0, 0.171], -25, [-0.128, 0, -0.228], 40],
};

function shot(kind) {
  return {
    clip(fit, model) {
      const name = `${kind}${fit === 'female' ? 'Female' : 'Male'}`;
      const key = beats(model);
      const keys = KEYS[name].map(({ t, ...b }) =>
        key(t, { clav: { l: [0, 0], r: [0, 0] }, ...b }),
      );
      const duration = keys.at(-1).t;
      const [lead, leadYaw, rear, rearYaw] = STANCE[name];
      const planted = {
        l: { pos: lead, pitch: 0, yaw: leadYaw, knee: 4 },
        r: { pos: rear, pitch: 0, yaw: rearYaw, knee: 4 },
      };
      keys.push({ t: 0, ease: 1, foot: planted });
      // The rifle's kick lifts the male's lead heel a touch.
      if (name === 'rifleMale')
        keys.push(
          { t: 0.08, foot: { l: { pos: lead, pitch: 0 } } },
          { t: 0.18, foot: { l: { pos: lead, pitch: -7 } } },
          { t: 0.32, ease: 1, foot: { l: { pos: lead, pitch: 0 } } },
        );
      keys.push({ t: duration, ease: 1, foot: planted });
      return {
        duration,
        loop: false,
        family: 'attack',
        bladeTravel: 'arm',
        bladeLimits: { flex: [-75, 85], dev: [-60, 30] },
        keys,
        lag: { head: 0.02, neck: 0.012 },
      };
    },
  };
}

export const rifle = shot('rifle');
export const bow = shot('bow');
