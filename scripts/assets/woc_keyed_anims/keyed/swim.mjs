function looped(table, family, { mirrored = false, legs = {} } = {}) {
  return {
    clip(fit, model) {
      const { duration, keys, feet: kicks = [], flex = -30 } = table[fit];
      const key = beats(model);
      const own = legs[fit];
      const beatsList = [
        ...keys.map((b) => (own ? (({ foot: _, ...rest }) => rest)(b) : b)),
        ...(own ? [] : kicks.map(([t, l, r]) => ({ t, foot: feet(l, r, flex) }))),
      ]
        .map((b) => (mirrored ? mirrorBeat(b) : b))
        .concat((own ?? []).map(([t, l, r]) => ({ t, foot: feet(l, r, flex) })));
      const authored = beatsList.map(({ t, ...b }) =>
        key(t, { clav: { l: [0, 0], r: [0, 0] }, ...b }),
      );
      // The loop closes on its first key.
      return {
        duration,
        loop: true,
        family,
        keys: [...authored, { ...authored[0], t: duration }],
        lag: { head: 0.04, neck: 0.03 },
      };
    },
  };
}

