const HOME_YAW = { male: { l: -16, r: 24 }, female: { l: -25, r: 40 } };

function longSwing(table, name) {
  return {
    clip(fit, model) {
      const key = beats(model);
      const { lead, rear } = SWORD_FEET[fit];
      const home = {
        l: { pos: lead, yaw: HOME_YAW[fit].l },
        r: { pos: rear, yaw: HOME_YAW[fit].r },
      };
      const planted = {
        l: { pos: lead, pitch: 0, yaw: home.l.yaw, knee: 6 },
        r: { pos: rear, pitch: 0, yaw: home.r.yaw, knee: 6 },
      };
      const steps = (STEPS[name]?.[fit] ?? []).map(([t, side, fields]) => ({
        t,
        foot: {
          [side]: Object.fromEntries(
            Object.entries(fields).map(([k, v]) => [k, v === 'home' ? home[side][k] : v]),
          ),
        },
      }));
      // The support hand only wraps the haft, so it is not aimed on its own: at
      // full reach its arm roll is free and separately aimed keys flip it.
      const authored = table[fit].map(({ t, blade, bladeFace, ...b }) =>
        key(t, {
          clav: { l: [0, 0], r: [0, 0] },
          blade: { r: blade.r },
          bladeFace: { r: bladeFace.r },
          ...b,
        }),
      );
      const duration = authored.at(-1).t;
      return {
        duration,
        loop: false,
        family: 'attack',
        bladeTravel: 'arm',
        bladeSteady: 2.5,
        bladeLimits: { flex: [-75, 85], dev: [-75, 30] },
        grip: { hand: 'l' },
        keys: [
          ...authored,
          { t: 0, ease: 1, foot: planted },
          ...steps,
          { t: duration, ease: 1, foot: planted },
        ],
        lag: { head: 0.02, neck: 0.012 },
      };
    },
  };
}

