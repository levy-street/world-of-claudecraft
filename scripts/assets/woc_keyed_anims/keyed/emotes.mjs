function emote(table, name) {
  return {
    clip(fit, model) {
      const { duration, keys } = table[fit];
      const key = beats(model);
      const stand = STAND[fit];
      const [leadPos, leadYaw, rearPos, rearYaw] = STAND_FEET[fit];
      const home = { l: { pos: leadPos, yaw: leadYaw }, r: { pos: rearPos, yaw: rearYaw } };
      const planted = {
        l: { pos: leadPos, pitch: 0, yaw: leadYaw, knee: 4 },
        r: { pos: rearPos, pitch: 0, yaw: rearYaw, knee: 4 },
      };
      const steps = (STEPS[name]?.[fit] ?? []).map(([t, side, fields]) => ({
        t,
        foot: {
          [side]: Object.fromEntries(
            Object.entries(fields).map(([k, v]) => [k, v === 'stand' ? home[side][k] : v]),
          ),
        },
      }));
      const authored = [
        key(0, { clav: { l: [0, 0], r: [0, 0] }, ...stand }),
        ...keys.map(({ t, ...b }) => key(t, b)),
        key(duration, { clav: { l: [0, 0], r: [0, 0] }, ...stand }),
      ];
      return {
        duration,
        loop: false,
        family: 'emote',
        bladeTravel: 'arm',
        bladeSteady: 6,
        bladeLimits: { flex: [-75, 85], dev: [-50, 30] },
        keys: [
          ...authored,
          { t: 0, ease: 1, foot: planted },
          ...steps,
          { t: duration, ease: 1, foot: planted },
        ],
        lag: { head: 0.03, neck: 0.02 },
      };
    },
  };
}

