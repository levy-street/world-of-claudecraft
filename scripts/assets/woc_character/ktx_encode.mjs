// KTX2 encoding for the split WOC character files (docs: the 2026-09-25 character size
// gameplan, "Encoder settings"). One call per lossless PNG master, through the `ktx` CLI
// directly: the gltf-transform toktx helper never applies RDO to normal maps, and every map
// here is encoded ONCE from its PNG master (never a decode and re-encode of an existing KTX2).
//
//   color / emissive  low: ETC1S (Basis-LZ) quality 128; medium/high: UASTC level 2, zstd 18,
//                     RDO lambda 1
//   ORM (data)        UASTC level 2, zstd 18, RDO lambda 1 (never ETC1S: it blotches packed data)
//   normal            UASTC level 2, zstd 18, RDO lambda 0.5 (a separate, gentler pass)
//   head hair (grey)  ETC1S quality 255, compression level 5 (hair_grey.mjs WOC_HAIR_GREY_KTX:
//                     the head packs' hair, scalp and beard textures, which ship grey)
//
// An ETC1S setting may name its compression level (`clevel`, 0 to 6); without one it is 1, the
// level every other ETC1S encode here has always used.
//
// The encoder generates each map's mip levels from that one master, except for a texture that
// brings its own (encodeLevels: the head core's atlas, whose levels are built per cell).
//
// Results are cached by content hash (the PNG bytes plus the settings) under tmp/, so a rebuild
// only re-encodes what changed. KTX_BIN names the directory holding `ktx` (and its dylibs on
// macOS); the default is the main checkout's tmp/ktx-software/bin, as compress_glb_textures.mjs.
import { execFile } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';

const run = promisify(execFile);

/** The settings per map kind and tier (gameplan "Encoder settings"). */
export function encoderSettings(kind, tier) {
  if (kind === 'normal') return { codec: 'uastc', srgb: false, rdo: 0.5 };
  if (kind === 'data') return { codec: 'uastc', srgb: false, rdo: 1.0 };
  // color and emissive
  if (tier === 'low') return { codec: 'etc1s', srgb: true, qlevel: 128 };
  return { codec: 'uastc', srgb: true, rdo: 1.0 };
}

/** The `ktx create` arguments for one image under `settings` (exported for its test). */
export function ktxArgs(settings, input, output) {
  const fmt = settings.srgb ? 'R8G8B8A8_SRGB' : 'R8G8B8A8_UNORM';
  const tf = settings.srgb ? 'srgb' : 'linear';
  const args = ['create', '--format', fmt, '--assign-tf', tf, '--generate-mipmap'];
  if (settings.codec === 'etc1s') {
    args.push(
      '--encode',
      'basis-lz',
      '--clevel',
      String(settings.clevel ?? 1),
      '--qlevel',
      String(settings.qlevel ?? 128),
    );
  } else {
    args.push('--encode', 'uastc', '--uastc-quality', '2', '--zstd', '18');
    if (settings.rdo) args.push('--uastc-rdo', '--uastc-rdo-l', String(settings.rdo));
  }
  args.push(input, output);
  return args;
}

/** The command for a texture whose mip levels are GIVEN: one input per level, level 0 first
 *  (the order `ktx create` reads them in), and no --generate-mipmap. Everything else is what
 *  ktxArgs passes: its own argument list with the generate flag swapped for the level count
 *  and the one input for all of them. */
function ktxLevelArgs(settings, inputs, output) {
  const args = ktxArgs(settings, inputs[0], output);
  args.splice(args.indexOf('--generate-mipmap'), 1, '--levels', String(inputs.length));
  args.splice(args.length - 2, 1, ...inputs);
  return args;
}

/** levelCount of a KTX2 file: the eighth 32 bit field after its 12 byte identifier. */
const ktx2LevelCount = (bytes) => bytes.readUInt32LE(40);

export function ktxBinDir(repoRoot) {
  if (process.env.KTX_BIN) return process.env.KTX_BIN;
  const candidates = [
    path.join(repoRoot, 'tmp', 'ktx-software', 'bin'),
    path.join(os.homedir(), 'world-of-claudecraft', 'tmp', 'ktx-software', 'bin'),
  ];
  const hit = candidates.find((d) => fs.existsSync(path.join(d, 'ktx')));
  if (!hit) throw new Error('ktx CLI not found: set KTX_BIN to the KTX-Software bin directory');
  return hit;
}

/**
 * An encoder bound to a cache directory and a concurrency limit. encode(png, settings) resolves
 * to the KTX2 bytes, its mip levels generated by the encoder from the one image.
 * encodeLevels(pngs, settings) takes the levels as given instead, level 0 first down to 1 x 1
 * (an atlas builds its own: a generator that filters the whole image averages each cell with
 * its neighbours, head_atlas.mjs headAtlasMipLevels), and resolves to the KTX2 that carries
 * exactly those.
 */
export function createKtxEncoder({
  repoRoot,
  cacheDir,
  concurrency = Math.max(2, os.cpus().length >> 1),
}) {
  const bin = ktxBinDir(repoRoot);
  fs.mkdirSync(cacheDir, { recursive: true });
  const env = { ...process.env, DYLD_FALLBACK_LIBRARY_PATH: bin, LD_LIBRARY_PATH: bin };
  let active = 0;
  const waiting = [];
  const slot = () =>
    active < concurrency
      ? (active++, Promise.resolve())
      : new Promise((resolve) => waiting.push(resolve)).then(() => {
          active++;
        });
  const release = () => {
    active--;
    const next = waiting.shift();
    if (next) next();
  };
  const stats = { encoded: 0, cached: 0 };
  // One encode per content key at a time: a set's left and right pieces often share one
  // master, and two jobs writing the same temp names race each other.
  const inFlight = new Map();
  let serial = 0;
  // `pngs` is the one image the encoder generates the levels of, or (`given`) every level.
  async function encodeOnce(key, pngs, settings, given) {
    const out = path.join(cacheDir, `${key}.ktx2`);
    if (fs.existsSync(out)) {
      stats.cached++;
      return fs.readFileSync(out);
    }
    await slot();
    const job = `${key}.${process.pid}.${serial++}`;
    const tmpIns = pngs.map((_png, k) =>
      path.join(cacheDir, given ? `${job}.in.${k}.png` : `${job}.in.png`),
    );
    const tmpOut = path.join(cacheDir, `${job}.tmp.ktx2`);
    try {
      pngs.forEach((png, k) => {
        fs.writeFileSync(tmpIns[k], png);
      });
      const args = given
        ? ktxLevelArgs(settings, tmpIns, tmpOut)
        : ktxArgs(settings, tmpIns[0], tmpOut);
      await run(path.join(bin, 'ktx'), args, { env });
      // a file that dropped a given level would be cached as the real thing: refuse it here
      const wrote = given ? ktx2LevelCount(fs.readFileSync(tmpOut)) : pngs.length;
      if (wrote !== pngs.length) throw new Error(`ktx wrote ${wrote} of ${pngs.length} levels`);
      fs.renameSync(tmpOut, out);
      stats.encoded++;
      return fs.readFileSync(out);
    } finally {
      for (const tmpIn of tmpIns) fs.rmSync(tmpIn, { force: true });
      fs.rmSync(tmpOut, { force: true });
      release();
    }
  }
  // The cache key covers the whole command, not just the settings: the exact argument list
  // ktxArgs builds (a changed flag re-encodes) and the ktx binary itself (a new KTX-Software
  // build re-encodes).
  const binStamp = (() => {
    const st = fs.statSync(path.join(bin, 'ktx'));
    return `${st.size}:${st.mtimeMs}`;
  })();
  function encode(png, settings) {
    const key = crypto
      .createHash('sha256')
      .update(png)
      .update(JSON.stringify(settings))
      .update(JSON.stringify(ktxArgs(settings, 'in', 'out')))
      .update(binStamp)
      .digest('hex');
    let pending = inFlight.get(key);
    if (!pending) {
      pending = encodeOnce(key, [png], settings, false).finally(() => inFlight.delete(key));
      inFlight.set(key, pending);
    }
    return pending;
  }
  // The key of a set of given levels covers every level's bytes (each behind its length, so
  // two sets never read as one stream) and the level command; the leading tag (no PNG starts
  // with it) keeps it apart from every key encode() makes.
  function encodeLevels(pngs, settings) {
    if (pngs.length === 0) throw new Error('encodeLevels: no levels');
    const hash = crypto.createHash('sha256').update('levels');
    for (const png of pngs) hash.update(`${png.length}:`).update(png);
    const names = pngs.map((_png, k) => `in${k}`);
    const key = hash
      .update(JSON.stringify(settings))
      .update(JSON.stringify(ktxLevelArgs(settings, names, 'out')))
      .update(binStamp)
      .digest('hex');
    let pending = inFlight.get(key);
    if (!pending) {
      pending = encodeOnce(key, pngs, settings, true).finally(() => inFlight.delete(key));
      inFlight.set(key, pending);
    }
    return pending;
  }
  return { encode, encodeLevels, stats };
}
