#!/usr/bin/env node
// Turns the trunk data Blender emitted into the table the Tree Generator reads.
//
//   1. Open Blender (BlenderMCP addon server running on 127.0.0.1:9876)
//   2. python3 ~/.claude/tools/blender_bridge.py run scripts/assets/build_trunks.py
//        -> public/models/foliage/trunks/*.glb  +  tmp/trunks.json
//   3. node scripts/assets/build_tree_trunks.mjs
//        -> src/render/tree_trunks.generated.ts
//
// The generated table is COMMITTED, so nobody needs Blender to build or run the
// game; you only need it to change the trunks themselves.
//
// The table exists because the GLB streams in asynchronously but the generator
// has to know the trunk's height, girth and branch sockets the instant a tree is
// placed - that is what lets it build branches, canopy volumes and collision
// synchronously and then drop the bark mesh in when it arrives.

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const IN = join(ROOT, 'tmp', 'trunks.json');
const OUT = join(ROOT, 'src', 'render', 'tree_trunks.generated.ts');

const raw = JSON.parse(await readFile(IN, 'utf8'));
const n = (v) => Number(v.toFixed(4));
const vec = (v) => `[${v.map(n).join(', ')}]`;

const body = raw
  .map((t) => {
    const sockets = t.sockets
      .map(
        (s) =>
          `      { p: ${vec(s.p)}, d: ${vec(s.d)}, r: ${n(s.r)}` +
          (s.tier !== undefined ? `, tier: ${n(s.tier)}` : '') +
          (s.crown ? ', crown: true' : '') +
          ' },',
      )
      .join('\n');
    return `  {
    key: '${t.key}',
    label: '${t.label}',
    kind: '${t.kind}',
    height: ${n(t.height)},
    baseRadius: ${n(t.baseRadius)},
    collideHeight: ${n(t.collideHeight)},
    crownY: ${n(t.crownY)},
    crownRadius: ${n(t.crownRadius)},
    verts: ${t.verts},
    sockets: [
${sockets}
    ],
  },`;
  })
  .join('\n');

const ts = `// GENERATED by scripts/assets/build_tree_trunks.mjs from tmp/trunks.json,
// which tmp/build_trunks.py writes out of Blender. Do not edit by hand.
//
// The foundation trunks the Tree Generator grows from: hand-modelled bark and
// limb silhouettes, in glTF axes (Y up), source units = yards. Sockets are the
// limb tips where the procedural branches and canopy volumes take over.

export interface TrunkSocket {
  /** Socket position in trunk-local yards (Y up). */
  p: readonly [number, number, number];
  /** Unit direction the limb was travelling when it ended. */
  d: readonly [number, number, number];
  /** Limb radius at the tip. */
  r: number;
  /** Conifer whorls only: 0 at the lowest whorl, 1 at the top. */
  tier?: number;
  /** The single crown socket of a palm: hang the whole canopy here. */
  crown?: boolean;
}

export interface TrunkDef {
  key: string;
  label: string;
  kind: string;
  /** Model height in source yards (tallest vertex). */
  height: number;
  /** Trunk girth at the foot: the collision footprint radius. */
  baseRadius: number;
  /** How much of the height is solid trunk worth colliding with. */
  collideHeight: number;
  /** Suggested canopy centre height and spread when a tree is first placed. */
  crownY: number;
  crownRadius: number;
  verts: number;
  sockets: readonly TrunkSocket[];
}

export const TRUNKS: readonly TrunkDef[] = [
${body}
];

export const DEFAULT_TRUNK = '${raw[0]?.key ?? 'oak'}';

export function trunkPath(key: string): string {
  return \`models/foliage/trunks/\${key}.glb\`;
}

export function trunkDef(key: string): TrunkDef | null {
  return TRUNKS.find((t) => t.key === key) ?? null;
}
`;

await writeFile(OUT, ts);
console.log(`wrote ${OUT.replace(`${ROOT}/`, '')} (${raw.length} trunks)`);
