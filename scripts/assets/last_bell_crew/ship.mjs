// The one command that takes a Last Bell figure from Blender to the game, with the
// concept book as the proof in the middle.
//
//   node scripts/assets/last_bell_crew/ship.mjs ollun,coalfast
//   node scripts/assets/last_bell_crew/ship.mjs all
//
// WHY THIS EXISTS. The book and the game used to be two sources of truth: the book
// placed held props in Blender, the game re-derived them at runtime from grip tables,
// and they drifted every single time. Now there is ONE artifact. A figure's fixed props
// are baked into its GLB (`crew.export`), the book photographs that shipped GLB
// (`plates.render_member`), and the renderer loads the same file. What you see on the
// page is what the game draws, structurally, not by anyone remembering to sync.
//
// The order below is the load-bearing part and it is not negotiable:
//   1. build + export RAW      (blender, model.py with CREW_OUT)
//   2. optimize into public/   (meshopt: the runtime loader cannot read a raw export)
//   3. photograph the SHIPPED file into plates  (blender, model.py with CREW_PLATES)
//   4. rebuild the book page from those plates
//   5. regenerate the media manifest so the new bytes reach prod
// Step 3 must follow step 2, or the book is once again a picture of something that
// never shipped, which is the exact bug this pipeline was built to make impossible.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..', '..', '..');
const MEMBERS = process.argv[2] ?? 'all';

// An ISOLATED staging dir per run. `build_assets.mjs` optimizes every GLB in its
// spec's srcDir, and the shared `tmp/asset_src/last_bell_crew/` still holds stale raw
// exports that would otherwise be re-optimized over shipped models.
const STAGE = join(REPO, 'tmp', 'asset_src', 'last_bell_ship');
const SPEC = join(REPO, 'tmp', 'last_bell_ship_spec.json');
const PLATES = join(REPO, 'tmp', 'crew_plates');

function blenderBin() {
  const explicit = process.env.BLENDER_PATH;
  if (explicit && existsSync(explicit)) return explicit;
  const mac = '/Applications/Blender.app/Contents/MacOS/Blender';
  if (existsSync(mac)) return mac;
  return 'blender';
}

function run(cmd, args, env = {}) {
  console.log(`\n> ${cmd.split('/').pop()} ${args.slice(-2).join(' ')}`);
  // Blender ships its own Python; an inherited PYTHONHOME/PYTHONPATH makes it fail to
  // import `encodings` and die before running a single line of the factory.
  const clean = { ...process.env, ...env };
  delete clean.PYTHONHOME;
  delete clean.PYTHONPATH;
  execFileSync(cmd, args, { cwd: REPO, stdio: 'inherit', env: clean });
}

rmSync(STAGE, { recursive: true, force: true });
mkdirSync(STAGE, { recursive: true });
mkdirSync(PLATES, { recursive: true });

const model = join(HERE, 'model.py');
const blender = blenderBin();

// 1. build + export raw
run(blender, ['--background', '--python', model], {
  CREW_MEMBER: MEMBERS,
  CREW_OUT: STAGE,
});

// 2. optimize into public/ (meshopt + texture clamp), geometry-safe `character` type
writeFileSync(
  SPEC,
  `${JSON.stringify(
    {
      note: 'Generated by ship.mjs. Isolated staging dir so no stale raw export is re-optimized over a shipped model.',
      items: [
        {
          srcDir: 'tmp/asset_src/last_bell_ship',
          outDir: 'models/chars/npcs',
          type: 'character',
          maxTex: 512,
        },
      ],
    },
    null,
    2,
  )}\n`,
);
run(process.execPath, [join(REPO, 'scripts', 'assets', 'build_assets.mjs'), SPEC]);

// 3. photograph what actually shipped
run(blender, ['--background', '--python', model], {
  CREW_MEMBER: MEMBERS,
  CREW_PLATES: PLATES,
  CREW_FROM_SHIPPED: '1',
});

// 4. rebuild the page, 5. regenerate the media manifest
run(process.execPath, [join(HERE, 'build_concept_book.mjs'), PLATES]);
run(process.execPath, [join(REPO, 'scripts', 'build_media_manifest.mjs'), 'generate']);

console.log(`
Shipped: ${MEMBERS}
  models  public/models/chars/npcs/
  book    docs/design/last-bell-concept-art.html  (open it directly, no server needed)
The page now shows the shipped GLBs, held props included. If a prop looks wrong on the
page it is wrong in the game too, which is the point.`);
