const radians = Math.PI / 180;
function turn(pose, bone, angles, amount = 1) {
  const key = `${bone}|rotation`;
  const value = pose.get(key);
  if (!value) throw new Error(`Shaman rig has no ${bone}`);
  const q = new Quaternion().fromArray(value);
  q.multiply(new Quaternion().setFromEuler(new Euler(...angles.map((v) => v * radians * amount))));
  pose.set(key, q.normalize().toArray());
}

/** Upper body uses authored donor silhouettes; stance solver owns the legs.
 * Keep translations, scale and sockets on idle so donor swings cannot slide
 * the feet, resize a weapon, or animate the held prop out of the hand. */
export function shamanPose(idle, index, time, chest, right, left, amount = 1) {
  const donor = mergePoses(samplePose(index, time), idle);
  const pose = new Map(idle);
  for (const [key, value] of donor) {
    if (/^(spine|chest|head|upperarm\.[rl]|lowerarm\.[rl]|hand\.[rl])\|rotation$/.test(key))
      pose.set(key, value);
  }
  turn(pose, 'chest', chest, amount);
  turn(pose, 'spine', [chest[0] * 0.22, chest[1] * 0.32, chest[2] * 0.2], amount);
  turn(pose, 'head', [-chest[0] * 0.35, -chest[1] * 0.45, -chest[2] * 0.3], amount);
  turn(pose, 'upperarm.r', right, amount);
  turn(pose, 'upperarm.l', left, amount);
  return pose;
}

export function mixShamanPose(a, b, weight) {
  return new Map(
    [...a].map(([key, value]) => [key, blendValue(key, value, b.get(key) ?? value, weight)]),
  );
}

export function breatheShamanPose(pose, phase, strength = 1) {
  const result = new Map(pose);
  turn(result, 'chest', [-1.8 * Math.sin(phase), 0.7 * Math.sin(phase), 0], strength);
  turn(result, 'upperarm.r', [1.5 * Math.sin(phase), 0, 0.7 * Math.sin(phase)], strength);
  turn(result, 'upperarm.l', [1.2 * Math.sin(phase), 0, -0.6 * Math.sin(phase)], strength);
  return result;
}
