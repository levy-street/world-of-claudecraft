/** Resolve from the actual caster's live enchantment, including remote actors. */
export function ritualVariantAbilityId(id: string, auras: readonly { id: string }[]): string {
  if (id !== 'unleash_weapon') return id;
  if (auras.some((a) => a.id === 'flametongue_weapon')) return 'unleash_weapon_pyrebrand';
  if (auras.some((a) => a.id === 'galeheart_weapon')) return 'unleash_weapon_galeheart';
  if (auras.some((a) => a.id === 'rockbiter_weapon')) return 'unleash_weapon_stonebound';
  if (auras.some((a) => a.id === 'lifespring_weapon')) return 'unleash_weapon_lifespring';
  return id;
}
