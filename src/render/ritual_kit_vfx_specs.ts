import type { RitualChoreography, RitualShape } from './ability_vfx/ritual_choreography_core';
import type { AbilityVfxArchetype, AbilityVfxFullSpec, AbilityVfxSpec } from './ability_vfx_core';

type Entry = {
  archetype: AbilityVfxArchetype;
  palette: string;
  tint: string;
  accent: string;
  power: number;
  ritual: RitualChoreography;
  weaponAura?: string;
};
function rite(
  shape: RitualShape,
  archetype: AbilityVfxArchetype,
  palette: string,
  tint: string,
  accent: string,
  radius: number,
  height: number,
  strands: number,
  twist: number,
  beats: readonly number[] = [0],
  power = 1,
  width = 0.065,
): Entry {
  return {
    archetype,
    palette,
    tint,
    accent,
    power,
    ritual: {
      shape,
      radius,
      height,
      strands,
      twist,
      beats: beats.map((time) => time * 0.5),
      width,
      duration: shape === 'precision' ? 0.2 : shape === 'edge' ? 0.3 : 0.32,
      anchor: archetype === 'buff' || archetype === 'summon' ? 'caster' : 'target',
    },
  };
}

