const k = (suffix: string): TranslationKey => `bossJournal.smithHeart.${suffix}` as TranslationKey;
const cast = (id: string): TranslationKey => `abilityUi.cast.${id}` as TranslationKey;
/** The tank buster alert's names (hud_chrome.ts tankBuster): the guide and the
 *  alert name a swingless buster the same. */
const buster = (key: string): TranslationKey => `hudChrome.tankBuster.${key}` as TranslationKey;

type Tier = JournalDifficulty;

/** A mechanic's damage labels (its `hits`) read off a boss template's own
 *  fields, a field the template lacks dropped. */
function named(...labels: readonly (string | undefined)[]): readonly string[] {
  return labels.filter((label): label is string => label !== undefined);
}

/** One value set per tier. */
function tiers(at: (tier: Tier) => JournalValues): Readonly<Record<Tier, JournalValues>> {
  return { normal: at('normal'), heroic: at('heroic') };
}

/** A tuned range at a tier's factor as `min`/`max` (the two-tier compare reads
 *  these), rounded the way every Smith's Heart fight rolls it. */
function span(min: number, max: number, mult: number): JournalValues {
  return { min: tierValue(min, mult), max: tierValue(max, mult) };
}

/** Forge-Fury, the raid's hard enrage: Heroic only, so its section is absent
 *  on Normal (a phase with no mechanic left is dropped). */
function forgeFury(boss: HeartEnrageBoss): JournalPhaseDef {
  const minutes = (HARD_ENRAGE_SECONDS[boss].heroic ?? 0) / 60;
  const E = HARD_ENRAGE_TUNING;
  return {
    id: 'forge-fury',
    nameKey: k('common.furyPhaseName'),
    summaryKey: k('common.furyPhaseSummary'),
    values: { minutes },
    mechanics: [
      {
        id: 'forge-fury',
        iconId: 'dgn_heart_forge_fury',
        hits: [HARD_ENRAGE_NAMES.fury],
        nameKey: k('common.furyName'),
        summaryKey: k('common.furySummary'),
        responseKey: k('common.furyResponse'),
        roles: ['all'],
        flags: ['deadly'],
        availability: 'heroic',
        values: {
          minutes,
          warn: E.warnLead,
          every: E.pulseEvery,
          share: E.pulseShare,
          share2: E.pulseShare * 2,
          kill: E.killPulse,
        },
        percentValues: ['share', 'share2'],
      },
    ],
  };
}

const heroicMinutes = (boss: HeartEnrageBoss): number =>
  (HARD_ENRAGE_SECONDS[boss].heroic ?? 0) / 60;

/** The banner chip naming the Heroic hard enrage (Heroic only). */
function enrageChip(boss: HeartEnrageBoss): JournalChipDef {
  return {
    key: k('common.chipEnrage'),
    values: { minutes: heroicMinutes(boss) },
    availability: 'heroic',
  };
}

