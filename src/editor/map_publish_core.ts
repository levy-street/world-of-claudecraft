// Publish-to-repo emit: the pure half of "Publish to Game". No DOM, no
// filesystem, no fetch, the same arrangement as regions/region_export_core.ts,
// so the dev-server endpoint and any future CLI write byte-identical files.
//
// A publish emits three artifacts:
//   data/maps/<slug>.map.json          the canonical MapDoc (editable source)
//   src/sim/maps/<slug>.generated.ts   the game-side module: the projected
//                                      WorldContent as lazy-memoized JSON
//                                      (thornhollow's convention, no parse
//                                      cost for players who never boot it),
//                                      with the catalogue collision boxes the
//                                      map uses VENDORED in, so a later
//                                      re-bake of the global table cannot
//                                      drift this map's collision from what
//                                      its maker playtested.
//   src/sim/maps/index.generated.ts    the registry the game client reads;
//                                      dynamic import() per map keeps every
//                                      map's bytes out of the main bundle.
//
// Byte stability is a contract: publishing twice with no edits must produce
// identical files (JSON.stringify over the same projection, sorted registry).

import { bakedBoxesForPath } from '../sim/asset_collision';
import type { WorldContent } from '../sim/types';

export const PUBLISH_MODULE_HEADER =
  '// GENERATED by ClaudeCraft Studio "Publish to Game" - do not edit by hand.';

const SLUG_MAX = 48;

/** A repo-safe slug from the map's display name. Deterministic; collisions
 *  between different names are the maker's to resolve by renaming. */
export function mapPublishSlug(name: string): string {
  const slug = name
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, SLUG_MAX)
    .replace(/_+$/g, '');
  return slug.length > 0 ? slug : 'untitled_map';
}

export function publishedMapPaths(slug: string): {
  mapJson: string;
  module: string;
  registry: string;
} {
  return {
    mapJson: `data/maps/${slug}.map.json`,
    module: `src/sim/maps/${slug}.generated.ts`,
    registry: `src/sim/maps/index.generated.ts`,
  };
}

/**
 * Freeze the catalogue collision this map depends on into the world itself.
 * `content.assetCollision` (path-keyed) is consulted BEFORE the global table
 * (sim/asset_collision.ts bakedBoxesForPath), so stamping the resolved boxes
 * for every placed path makes the published map self-contained: render and
 * collision derive from the same committed bytes forever. Existing entries
 * (imported-model bakes) always win.
 */
export function vendorPublishedAssetCollision(world: WorldContent): WorldContent {
  const placements = world.placements ?? [];
  if (placements.length === 0) return world;
  const vendored: Record<string, unknown> = { ...(world.assetCollision ?? {}) };
  const seen = new Set<string>(Object.keys(vendored));
  for (const p of placements) {
    const path = p.path;
    if (!path || seen.has(path)) continue;
    seen.add(path);
    const boxes = bakedBoxesForPath(path);
    // Empty box lists are deliberate walk-throughs (stairs) and the override
    // channel ignores empties anyway; only real shapes are worth pinning.
    if (boxes && boxes.length > 0) vendored[path] = boxes.map((b) => ({ ...b }));
  }
  if (Object.keys(vendored).length === 0) return world;
  return { ...world, assetCollision: vendored as WorldContent['assetCollision'] };
}

/** The game-side module for one published map. `worldJson` is the projected
 *  (and vendored) WorldContent, already serialized by the caller so the emit
 *  cannot introduce nondeterminism of its own. */
export function emitPublishedMapModule(
  slug: string,
  name: string,
  seed: number,
  worldJson: string,
): string {
  return `${PUBLISH_MODULE_HEADER}
// Canonical source: data/maps/${slug}.map.json (open it in Studio to edit,
// then publish again). Loaded through src/sim/maps/index.generated.ts.
import type { WorldContent } from '../types';

export const MAP_SLUG = ${JSON.stringify(slug)};
export const MAP_NAME = ${JSON.stringify(name)};
export const MAP_SEED = ${JSON.stringify(seed)};

// Lazy-memoized JSON (the thornhollow convention): parsing is deferred to the
// first boot of this map, so the module costs ~no startup time if it is ever
// bundled eagerly. The registry still dynamic-imports it, so in the normal
// path even these bytes stay out of the main chunk.
const __map_json = ${JSON.stringify(worldJson)};
let __map: WorldContent | null = null;
export function loadPublishedMap(): WorldContent {
  return (__map ??= JSON.parse(__map_json) as WorldContent);
}
`;
}

/** The registry module over every published map, sorted by slug. */
export function emitPublishedMapRegistry(
  entries: readonly { slug: string; name: string; seed: number }[],
): string {
  const sorted = [...entries].sort((a, b) => a.slug.localeCompare(b.slug));
  const rows = sorted
    .map(
      (e) =>
        `\n  {\n    slug: ${JSON.stringify(e.slug)},\n    name: ${JSON.stringify(e.name)},\n    seed: ${JSON.stringify(e.seed)},\n    load: async () => (await import('./${e.slug}.generated')).loadPublishedMap(),\n  },`,
    )
    .join('');
  return `${PUBLISH_MODULE_HEADER}
// The registry of Studio-published maps. The game client boots one with
// ?map=<slug> (src/main.ts); dynamic import keeps map bytes out of the main
// bundle until a map is actually chosen.
import type { WorldContent } from '../types';

export interface PublishedMapEntry {
  slug: string;
  name: string;
  seed: number;
  load(): Promise<WorldContent>;
}

export const PUBLISHED_MAPS: readonly PublishedMapEntry[] = [${rows}
];

export function publishedMapBySlug(slug: string): PublishedMapEntry | undefined {
  return PUBLISHED_MAPS.find((m) => m.slug === slug);
}
`;
}
