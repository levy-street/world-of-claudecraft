// Korzul the Gravewyrm drank dry. Zar'Keth, the Sunken Crown, a sun-court
// city older than Eastbrook, bound a shard of the Wyrm's own fire (the First
// Ember) to relight their dying kingdom; it burned the city to glass in one
// night. Only the Heartspring still runs, fed by veins that pass beneath the
// Wyrm's prison. Now the Ashen Court keeps a dead king's protocol in the
// ruins, the Emberveil (a Wyrmcult splinter) digs for the Ember to carry it
// home and burn the Sanctum seal open, and a caravan out of Highwatch has
// raised the Last Well beside the spring to stop them.
//
// This module is data-only and base-world-safe: its NPCs are registered
// `dynamic: true` (never surface-spawned in the base world; the custom map's
// content.npcs carries the live copies at real coordinates), and its ground
// objects register with EMPTY position lists (the map document places the
// real sparkles). Mobs/items/quests ride the normal merged registries so the
// custom map's camps and quest chain resolve.

